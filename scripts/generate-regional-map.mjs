import { readFileSync, writeFileSync } from "node:fs";
import { geoNaturalEarth1, geoPath } from "d3-geo";

const WIDTH = 960;
const HEIGHT = 596;
const PADDING = 4;
const CELL_SIZE = 4;
const CELL_STEP = 6;

const countryAliases = {
  "cote divoire": "ivory coast",
  "côte divoire": "ivory coast",
  "dem rep congo": "democratic republic of the congo",
  "democratic republic of congo": "democratic republic of the congo",
  "dr congo": "democratic republic of the congo",
  "republic of congo": "republic of the congo",
  "the gambia": "gambia",
  "united republic of tanzania": "tanzania",
};

function normaliseCountryName(value) {
  const normalised = value
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, " ")
    .trim();

  return countryAliases[normalised] ?? normalised;
}

const africa = JSON.parse(readFileSync("data/africa.json", "utf8"));
const locationsSource = readFileSync("data/sovran-locations.ts", "utf8");
const locationCountries = new Set(
  [...locationsSource.matchAll(/country:\s*"([^"]+)"/g)].map((match) =>
    normaliseCountryName(match[1]),
  ),
);

const projection = geoNaturalEarth1().fitExtent(
  [
    [PADDING, PADDING],
    [WIDTH - PADDING, HEIGHT - PADDING],
  ],
  africa,
);

projection.scale(projection.scale() * 1.38);

const initialPath = geoPath(projection);
const [[scaledLeft, scaledTop], [scaledRight]] = initialPath.bounds(africa);
const [translateX, translateY] = projection.translate();
projection.translate([
  translateX + WIDTH / 2 - (scaledLeft + scaledRight) / 2,
  translateY + PADDING - scaledTop,
]);

const path = geoPath(projection).digits(0);
const [[mapLeft, mapTop]] = path.bounds(africa);
const countries = {};

for (const feature of africa.features) {
  const countryName = normaliseCountryName(feature.properties.name);
  if (!locationCountries.has(countryName)) continue;

  countries[countryName] = path(feature);
}

for (const country of locationCountries) {
  if (!countries[country]) {
    throw new Error(`No geographic path was generated for ${country}.`);
  }
}

const output = {
  width: WIDTH,
  height: HEIGHT,
  cellSize: CELL_SIZE,
  cellStep: CELL_STEP,
  patternX: Math.round((mapLeft - CELL_SIZE / 2) * 10) / 10,
  patternY: Math.round((mapTop - CELL_SIZE / 2) * 10) / 10,
  africaPath: path(africa),
  countries,
};

writeFileSync(
  "data/regional-map.generated.ts",
  `/* This file is generated by npm run map:build. */\nexport const REGIONAL_MAP_GEOMETRY = ${JSON.stringify(output, null, 2)} as const;\n`,
);
